package ke.ku.sco310.qr.render;

import ke.ku.sco310.qr.api.BoundPropertySource;
import ke.ku.sco310.qr.api.QrCode;
import ke.ku.sco310.qr.api.QrCodeRenderer;
import ke.ku.sco310.qr.api.QrRenderingException;
import ke.ku.sco310.qr.api.RenderedArtifact;
import ke.ku.sco310.qr.editor.HexColorPropertyEditor;

import java.beans.PropertyChangeListener;
import java.beans.PropertyChangeSupport;
import java.io.Serializable;
import java.nio.charset.StandardCharsets;
import java.util.Locale;

/**
 * Vector renderer component: emits an SVG document instead of a raster image.
 *
 * <p>Interchangeability note: this component implements the same
 * {@link QrCodeRenderer} interface as {@link PngRendererBean} and returns the same
 * {@link RenderedArtifact} type, yet the produced artifact has no pixels at all. Callers that
 * only use the interface keep working, which is the practical meaning of replaceability in
 * component-oriented programming.</p>
 *
 * <p>A printing-oriented property, {@code physicalWidthMillimetres}, writes absolute
 * millimetre dimensions into the SVG root so that a print shop can scale the symbol exactly.</p>
 */
public class SvgRendererBean implements QrCodeRenderer, Serializable, BoundPropertySource {

    private static final long serialVersionUID = 1L;

    /** Component instance identifier. */
    public static final String COMPONENT_ID = "renderer.svg.v1";

    private transient PropertyChangeSupport propertyChanges = new PropertyChangeSupport(this);

    private int moduleSize = 8;
    private int quietZone = 4;
    private String foregroundColor = "#000000";
    private String backgroundColor = "#FFFFFF";
    private boolean mergeHorizontalRuns = true;
    private double physicalWidthMillimetres = 0d;

    public SvgRendererBean() {
    }

    @Override
    public RenderedArtifact render(QrCode symbol) throws QrRenderingException {
        int moduleCount = symbol.getSize() + 2 * quietZone;
        int pixelSize = moduleCount * moduleSize;
        StringBuilder svg = new StringBuilder(4096);
        svg.append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
        svg.append("<svg xmlns=\"http://www.w3.org/2000/svg\" version=\"1.1\"")
           .append(" viewBox=\"0 0 ").append(pixelSize).append(' ').append(pixelSize).append('"')
           .append(" width=\"").append(pixelSize).append('"')
           .append(" height=\"").append(pixelSize).append('"');
        if (physicalWidthMillimetres > 0) {
            svg.append(" width=\"").append(format(physicalWidthMillimetres)).append("mm\"")
               .append(" height=\"").append(format(physicalWidthMillimetres)).append("mm\"");
        }
        svg.append(" shape-rendering=\"crispEdges\">\n");
        svg.append("  <title>QR Code v").append(symbol.getVersion())
           .append(" level ").append(symbol.getErrorCorrection().getLabel())
           .append(" mask ").append(symbol.getMask()).append("</title>\n");
        svg.append("  <desc>Generated by SCO310 component suite; payload length ")
           .append(symbol.getCharacterCount()).append(" characters</desc>\n");
        svg.append("  <rect width=\"100%\" height=\"100%\" fill=\"").append(backgroundColor).append("\"/>\n");
        svg.append("  <g fill=\"").append(foregroundColor).append("\">\n");

        int rectangles = 0;
        for (int y = 0; y < symbol.getSize(); y++) {
            int x = 0;
            while (x < symbol.getSize()) {
                if (!symbol.isDark(x, y)) {
                    x++;
                    continue;
                }
                int runEnd = x;
                if (mergeHorizontalRuns) {
                    while (runEnd + 1 < symbol.getSize() && symbol.isDark(runEnd + 1, y)) {
                        runEnd++;
                    }
                }
                svg.append("    <rect x=\"").append((quietZone + x) * moduleSize)
                   .append("\" y=\"").append((quietZone + y) * moduleSize)
                   .append("\" width=\"").append((runEnd - x + 1) * moduleSize)
                   .append("\" height=\"").append(moduleSize).append("\"/>\n");
                rectangles++;
                x = runEnd + 1;
            }
        }
        svg.append("  </g>\n</svg>\n");

        RenderedArtifact artifact = new RenderedArtifact();
        artifact.setContent(svg.toString().getBytes(StandardCharsets.UTF_8));
        artifact.setFormatName("SVG");
        artifact.setFileExtension("svg");
        artifact.setMimeType("image/svg+xml");
        artifact.setWidth(pixelSize);
        artifact.setHeight(pixelSize);
        artifact.setTextual(true);
        artifact.setRendererId(COMPONENT_ID + " (" + rectangles + " rects)");
        return artifact;
    }

    /** @return number of {@code <rect>} elements this configuration would emit. */
    public int countRectangles(QrCode symbol) {
        int count = 0;
        for (int y = 0; y < symbol.getSize(); y++) {
            int x = 0;
            while (x < symbol.getSize()) {
                if (!symbol.isDark(x, y)) {
                    x++;
                    continue;
                }
                int runEnd = x;
                if (mergeHorizontalRuns) {
                    while (runEnd + 1 < symbol.getSize() && symbol.isDark(runEnd + 1, y)) {
                        runEnd++;
                    }
                }
                count++;
                x = runEnd + 1;
            }
        }
        return count;
    }

    private static String format(double value) {
        return String.format(Locale.ROOT, "%.2f", value);
    }

    @Override
    public String getRendererId() {
        return COMPONENT_ID;
    }

    @Override
    public String getFormatName() {
        return "SVG";
    }

    @Override
    public String getFileExtension() {
        return "svg";
    }

    @Override
    public String getMimeType() {
        return "image/svg+xml";
    }

    @Override
    public String describeConfiguration() {
        return "SVG: moduleSize=" + moduleSize + "px, quietZone=" + quietZone + " modules, fg="
                + foregroundColor + ", bg=" + backgroundColor + ", mergedRuns=" + mergeHorizontalRuns
                + ", physicalWidth=" + (physicalWidthMillimetres > 0
                        ? format(physicalWidthMillimetres) + "mm" : "not set");
    }

    // ------------------------------------------------------------------ properties

    public int getModuleSize() {
        return moduleSize;
    }

    public void setModuleSize(int moduleSize) {
        int old = this.moduleSize;
        this.moduleSize = moduleSize;
        propertyChanges.firePropertyChange("moduleSize", old, moduleSize);
    }

    public int getQuietZone() {
        return quietZone;
    }

    public void setQuietZone(int quietZone) {
        int old = this.quietZone;
        this.quietZone = quietZone;
        propertyChanges.firePropertyChange("quietZone", old, quietZone);
    }

    public String getForegroundColor() {
        return foregroundColor;
    }

    public void setForegroundColor(String foregroundColor) {
        String old = this.foregroundColor;
        this.foregroundColor = HexColorPropertyEditor.toHex(HexColorPropertyEditor.fromHex(foregroundColor));
        propertyChanges.firePropertyChange("foregroundColor", old, this.foregroundColor);
    }

    public String getBackgroundColor() {
        return backgroundColor;
    }

    public void setBackgroundColor(String backgroundColor) {
        String old = this.backgroundColor;
        this.backgroundColor = HexColorPropertyEditor.toHex(HexColorPropertyEditor.fromHex(backgroundColor));
        propertyChanges.firePropertyChange("backgroundColor", old, this.backgroundColor);
    }

    public boolean isMergeHorizontalRuns() {
        return mergeHorizontalRuns;
    }

    /** Bound property: merging adjacent modules shrinks the document substantially. */
    public void setMergeHorizontalRuns(boolean mergeHorizontalRuns) {
        boolean old = this.mergeHorizontalRuns;
        this.mergeHorizontalRuns = mergeHorizontalRuns;
        propertyChanges.firePropertyChange("mergeHorizontalRuns", old, mergeHorizontalRuns);
    }

    public double getPhysicalWidthMillimetres() {
        return physicalWidthMillimetres;
    }

    public void setPhysicalWidthMillimetres(double physicalWidthMillimetres) {
        double old = this.physicalWidthMillimetres;
        this.physicalWidthMillimetres = physicalWidthMillimetres;
        propertyChanges.firePropertyChange("physicalWidthMillimetres", old, physicalWidthMillimetres);
    }

    public void addPropertyChangeListener(PropertyChangeListener listener) {
        propertyChanges.addPropertyChangeListener(listener);
    }

    public void removePropertyChangeListener(PropertyChangeListener listener) {
        propertyChanges.removePropertyChangeListener(listener);
    }

    private void readObject(java.io.ObjectInputStream in) throws java.io.IOException, ClassNotFoundException {
        in.defaultReadObject();
        propertyChanges = new PropertyChangeSupport(this);
    }

    @Override
    public String toString() {
        return describeConfiguration();
    }
}
